@register.simple_tag
def sa_icon(name, cls="h-4 w-4"):
    # Some icons are several sub-paths joined by " M"; each becomes its own <path>.
    segs = ICONS.get(name, ICONS["info"]).split(" M")
    parts = "".join(
        format_html('<path stroke-linecap="round" stroke-linejoin="round" d="{}"/>', s if i == 0 else "M" + s)
        for i, s in enumerate(segs)
    )
    return format_html(
        '<svg class="{}" fill="none" viewBox="0 0 24 24" stroke="currentColor" stroke-width="1.6" aria-hidden="true">{}</svg>',
        cls, mark_safe(parts),
    )


@register.simple_tag(takes_context=True)
def sa_sort(context, key, label, align=""):
    """A sortable <th> link: click toggles asc/desc for `key`."""
    request = context["request"]
    current = context.get("sort", "")
    params = request.GET.copy()
    params.pop("page", None)
    active = current.lstrip("-") == key
    desc = current.startswith("-")
    params["sort"] = key if (active and desc) else f"-{key}" if active else key
    arrow = ("↓" if desc else "↑") if active else "↕"
    return format_html(
        '<a href="?{}" class="sa-sort{}{}">{}<span class="sa-sort-arrow">{}</span></a>',
        params.urlencode(), " sa-sort--active" if active else "", " justify-end" if align == "right" else "",
        label, arrow,
    )


